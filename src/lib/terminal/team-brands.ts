export function teamBrand(league: string, code: string): { name: string; logoUrl: string } | null {
  const team = TEAMS[league]?.[code];
  if (!team) return null;
  return {
    name: team[0],
    logoUrl: league === "nba"
      ? `https://cdn.nba.com/logos/nba/${team[1]}/primary/L/logo.svg`
      : `https://a.espncdn.com/i/teamlogos/${league}/500/${team[1]}.png`,
  };
}
